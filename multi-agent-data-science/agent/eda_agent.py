_EDA_TOOL_NAMES = {
    "profile_training_data",
    "compute_correlation_matrix",
    "generate_eda_charts",
    "select_candidate_models_and_metrics",
}
_MAX_NO_TOOL_ROUNDS = 2


def _trim_messages_to_current_round(messages: list[Any]) -> list[Any]:
    """Filter out historical messages, retaining only the tool call/response chains relevant to the current EDA subgraph.

    This prevents lengthy Markdown reports generated by upstream (data_clean) stages from cluttering the context,
    which could cause the LLM to lose focus and turn into a "parrot."
    """
    if not messages:
        return []

    last_eda_tool_idx: int | None = None
    for i in range(len(messages) - 1, -1, -1):
        msg = messages[i]
        if isinstance(msg, ToolMessage):
            if msg.name in _EDA_TOOL_NAMES:
                last_eda_tool_idx = i
            break

    if last_eda_tool_idx is None:
        return []

    start = last_eda_tool_idx
    for j in range(last_eda_tool_idx - 1, -1, -1):
        msg = messages[j]
        if isinstance(msg, ToolMessage) and msg.name in _EDA_TOOL_NAMES:
            start = j
            continue
        if isinstance(msg, AIMessage) and getattr(msg, "tool_calls", None):
            names = {tc.get("name") for tc in msg.tool_calls}
            if names & _EDA_TOOL_NAMES:
                start = j
                continue
        break

    return messages[start:]


def _merge_eda_report(state: GlobalState, tool_name: str, payload: dict[str, Any]) -> dict[str, Any]:
    existing = dict(state.get("eda_report") or {})
    steps = list(existing.get("steps", []))
    steps.append({"tool": tool_name, "result": payload})
    existing["steps"] = steps
    if tool_name == "generate_eda_charts" and isinstance(payload.get("charts"), list):
        existing["charts"] = payload["charts"]
        existing["chart_output_dir"] = payload.get("output_dir", "")
    return existing


def _eda_node(state: GlobalState) -> GlobalState:
    messages = state["messages"]
    training_data_path = state.get("training_data_path")
    task_type = (state.get("task_type") or "unknown").lower()
    target_column = state.get("target_column") or ""
    description = state.get("description") or ""
    testing_data_path = state.get("testing_data_path") or ""
    description_file_path = state.get("description_file_path") or ""

    # ── Idle detection: If the LLM did not call any tools in the previous round, increment the cumulative count ──
    no_tool_rounds = state.get("eda_no_tool_rounds", 0)
    if messages:
        last_msg = messages[-1]
        if isinstance(last_msg, AIMessage) and not getattr(last_msg, "tool_calls", None):
            no_tool_rounds += 1

    # ── Reaching the limit: Forced termination to prevent an infinite loop ──────────────────────
    if no_tool_rounds >= _MAX_NO_TOOL_ROUNDS:
        print(f"[eda_agent] EDA has not called any tools for {no_tool_rounds} consecutive rounds; the pipeline has been forcibly terminated.")
        # Simply set `supervisor_retry` to a very large value so that the main graph decides to give up
        retries = dict(state.get("supervisor_retry") or {})
        retries["eda"] = 999
        return {
            "eda_no_tool_rounds": 0,
            "supervisor_retry": retries,
            "messages": [
                AIMessage(
                    content=(
                        f"[forced terminate] The EDA agent has not called the tool for {no_tool_rounds} consecutive rounds; the pipeline has been forcibly terminated."
                    )
                )
            ],
        }

    pool = CLASSIFICATION_POOL if task_type == "classification" else REGRESSION_POOL
    pool_str = ", ".join(pool)
    metrics_allowed = CLASSIFICATION_METRICS if task_type == "classification" else REGRESSION_METRICS
    metrics_str = ", ".join(sorted(metrics_allowed))

    run_dir = state.get("run_dir") or ""

    supervisor_hint = (state.get("supervisor_hints") or {}).get("eda", "").strip()
    hint_line = (
        f"[Supervisor Feedback] Failed the previous review:{supervisor_hint}\n"
        "Please make sure to complete all four tool calls in sequence before generating the final response.\n"
        if supervisor_hint else ""
    )

    description_block = (
        f"Data Set Description (for reference only to understand column meanings; not to be used as a basis for business recommendations):{description}"
        if description
        else "Dataset description: Not provided"
    )

    system_content = (
        "You are an EDA (Exploratory Data Analysis) Agent responsible for analyzing the training set, developing a feature engineering plan, and selecting three candidate models,"
        "and determine the evaluation criteria for this mission."
        f"Training data path: {training_data_path or 'Not provided'}.\n"
        f"{description_block}。\n"
        f"Task Type:{task_type}。\n"
        f"Target column: {target_column or 'Not provided'}.\n"
        f"Current working directory: {run_dir or 'Not set'}.\n"
        + hint_line
        + "Workflow (executed in sequence):\n"
        "1. Call `profile_training_data` to retrieve the training dataset profile;\n"
        "2. Call `compute_correlation_matrix` to calculate the feature correlation matrix (passing in the target column name)\n"
        "3. Call `generate_eda_charts` to generate the complete EDA charts:"
        f"fPass the path to the training set as `file_path`, the target column as `target_column`, and `{task_type}` as `task_type`,"
        f"Pass the test dataset path `{testing_data_path}` to `test_file_path`,"
        f"output_dir ：{run_dir + '/plots' if run_dir else ''}(If left blank, the default path will be used)，"
        f"description_file Input:`{description_file_path}`（(Skip if empty),"
        "parameters ``description_text`` Leave it blank by default (do not paste the entire description into the tool parameters to avoid wasting tokens);"
        "The column descriptions are derived from the above document.\n"
        "4. Based on the above analysis, when calling `select_candidate_models_and_metrics` to submit the final decision, the following must be determined simultaneously:\n"
        f" [Model Selection] Candidate model pool ({task_type}): {pool_str}, select exactly 3 models; model names must match exactly;\n"
        f" [Evaluation Metrics] Optional metrics: {metrics_str}.\n"
        "   You must specify two indicator names (you must use the valid indicator names listed above; no other strings are permitted):\n"
        "  · primary_metric (1): The optimization objective for CV parameter tuning; select based on the following principles:\n"
        "     [Category]\n"
        "       Focus on class balance and overall accuracy → f1_weighted\n"
        "       Few classes present; need to monitor the risk of class imbalance → f1_macro\n"
        "       (Since macro weights each class equally, CV scores drop immediately when a minority class performs poorly, exposing model unevenness)\n"
        "       Severe imbalance → ROC AUC (requires predict_proba) or recall\n"
        "       Multi-class classification (number of classes > 2) → Prioritize f1_macro or f1_weighted;\n"
        "         roc_auc will automatically be upgraded to ovr_weighted, but if the candidate model includes an SVM, f1_macro will be selected instead\n"
        "       Probability calibration scenarios (CTR, click-through rate, risk score) → log_loss\n"
        "       (Note: All candidate models must support `predict_proba`. SVM does not support this by default and should be removed from the list of candidates.)\n"
        "     [Return] Default → r2 (global goodness-of-fit, intuitive); if there are obvious outliers → mae (more robust to outliers);\n"
        "      If the target variable is significantly skewed (skewness > 1 in the profile, e.g., housing prices, sales volume, or traffic) → use rmsle (which is more robust to skewness);\n"
        "     Business-oriented percentage deviation with no zero values in the target column → MAPE (highly readable for business purposes; deviation of X percent; suitable for sales/financial forecasting scenarios)；\n"
        "     The `max_error` parameter is rarely used; it is only considered in scenarios requiring high precision (such as part tolerances).\n"
        "   · evaluation_metrics (2–4 lists): Metrics for the final test set summary report,"
        "     primary_metric 必须包含在内，可加 1~2 个互补指标；\n"
        "     分类强烈建议：同时包含 f1_macro 和 f1_weighted，前者暴露少数类风险，后者反映整体分布下的表现；\n"
        "     回归建议：偏态目标值场景可加 max_error 观察最坏情况\n"
        "   · metrics_rationale：结合数据画像和业务目标，说明选择上述指标的原因。\n"
        "完成上述 4 个工具调用后，输出最终文字回复，内容严格限定为以下四项：\n"
        "  (1) 数据画像关键发现（缺失值、异常值、分布特征）；\n"
        "  (2) 相关矩阵分析结论（列出前几名相关特征，注明方向，指出疑似泄漏特征但不要描述删除操作——删除由 Feature Agent 执行）；\n"
        "  (3) 候选模型选择理由；\n"
        "  (4) 评估指标决策理由。\n"
        "【严禁事项】：\n"
        "  - 重要约束：你必须通过 tool_call 调用上述 4 个工具完成步骤 1~4，"
        "禁止只输出文字描述假装已完成。即使上游 data_clean / agent_manager 报告很长，"
        "你也必须独立执行 EDA 工具，不得复述上游内容、不得编造\"环境限制\"；\n"
        "  - 不得虚构或预测特征工程的执行结果（如「已进行 one-hot 编码」「已删除 duration」）；\n"
        "  - 不得虚构或预测模型训练、调参、CV 分数、测试集评估等任何后续阶段的结果；\n"
        "  - 不得编写业务建议、最终模型选择结论或完整流水线总结；\n"
        "  - EDA 报告只覆盖你实际执行的 4 个工具调用的真实输出，不得延伸至其他 Agent 的职责范围；\n"
        "  - 严禁出现以下任何章节标题（中英文）：\n"
        "    · 中文：业务建议 / 业务影响 / 业务洞察 / 业务推荐 / 业务价值 / 业务意义 /\n"
        "      行动建议 / 推荐操作 / 策略建议 / 战略建议 / 下一步 / 下一步行动 / 下一步操作 / 后续行动\n"
        "    · 英文：Business Recommendation(s) / Business Insight(s) / Business Action(s) /\n"
        "      Business Implication(s) / Business Value / Recommendation(s) / Recommended Action(s) /\n"
        "      Next Step(s) / Action Item(s) / Strategic Implication(s) / Strategic Recommendation(s)\n"
        "  - 业务建议由 business_translator_agent 在最终 business_insight_report.md 中统一产出；\n"
        "    若你违规输出上述章节，落盘前会被 save_agent_report 的过滤器自动剥离。"
    )

    # ── 关键修复：只把本轮 EDA 工具调用链送给 LLM ─────────────────────────
    # 首轮裁剪结果为空时，必须彻底丢弃整个 messages 历史（特别是 user_request
    # HumanMessage 与 agent_manager 的 RAP wrap-up AIMessage），仅以 SystemMessage
    # + 一条强约束 HumanMessage 启动 EDA，避免业务语境渗入。
    trimmed_history = _trim_messages_to_current_round(messages)
    if trimmed_history:
        llm_input = [SystemMessage(content=system_content), *trimmed_history]
    else:
        llm_input = [
            SystemMessage(content=system_content),
            HumanMessage(
                content=(
                    "请按系统提示词第 1~4 步逐个调用工具完成 EDA，禁止只输出文字描述。"
                    "禁止复读上游 data_clean / agent_manager 报告，"
                    "禁止生成业务建议、推荐操作、下一步、Recommendations、Next Steps 等业务类章节。"
                )
            ),
        ]

    response = llm_with_tools.invoke(llm_input)
    return {
        "messages": [response],
        "eda_no_tool_rounds": no_tool_rounds,
    }


def _tool_state_update_node(state: GlobalState) -> GlobalState:
    last_msg = state["messages"][-1]
    if not isinstance(last_msg, ToolMessage) or not last_msg.name:
        return {}

    handlers = {
        "profile_training_data": _handle_eda_step,
        "compute_correlation_matrix": _handle_eda_step,
        "generate_eda_charts": _handle_eda_step,
        "select_candidate_models_and_metrics": _handle_select_models,
    }
    handler = handlers.get(last_msg.name)
    return handler(state, last_msg) if handler else {}


def _parse_tool_payload(tool_message: ToolMessage) -> dict[str, Any]:
    try:
        return json.loads(str(tool_message.content))
    except json.JSONDecodeError:
        return {"error": {"type": "JSONDecodeError", "message": "工具输出不是合法 JSON"}}


def _handle_eda_step(state: GlobalState, tool_message: ToolMessage) -> GlobalState:
    payload = _parse_tool_payload(tool_message)
    report = _merge_eda_report(state, tool_message.name, payload)
    if "error" in payload:
        return {
            "eda_report": report,
            "current_stage": "eda_step_failed",
            "errors": (state.get("errors") or [])
            + [{"stage": "eda", "tool": tool_message.name, **payload["error"]}],
        }
    update: GlobalState = {
        "eda_report": report,
        "current_stage": "eda_step_done",
    }
    if tool_message.name == "generate_eda_charts" and isinstance(payload.get("charts"), list):
        update["eda_charts"] = payload["charts"]
    return update


def _handle_select_models(state: GlobalState, tool_message: ToolMessage) -> GlobalState:
    payload = _parse_tool_payload(tool_message)
    report = _merge_eda_report(state, tool_message.name, payload)
    if "error" in payload:
        return {
            "eda_report": report,
            "current_stage": "eda_model_selection_failed",
            "errors": (state.get("errors") or [])
            + [{"stage": "eda_model_selection", **payload["error"]}],
        }
    return {
        "eda_report": report,
        "candidate_models": payload["selected_models"],
        "feature_engineering_plan": payload["feature_engineering_plan"],
        "model_selection_plan": payload["model_selection_plan"],
        "primary_metric": payload.get("primary_metric", ""),
        "evaluation_metrics": payload.get("evaluation_metrics", []),
        "metrics_rationale": payload.get("metrics_rationale", ""),
        "current_stage": "eda_done",
        "next_action": "run_feature_engineering",
        "eda_no_tool_rounds": 0,
    }


def _route_after_eda(state: GlobalState) -> str:
    last_msg = state["messages"][-1]
    if isinstance(last_msg, AIMessage) and last_msg.tool_calls:
        return "tools"
    save_agent_report("eda_agent", last_msg, run_dir=state.get("run_dir") or "")
    return "timer_end"


def _show_graph_if_needed(agent_graph, show_graph: bool) -> None:
    if not show_graph:
        return
    try:
        output_dir = PROJECT_ROOT / "artifacts" / "graphs"
        output_dir.mkdir(parents=True, exist_ok=True)
        mmd_path = output_dir / "eda_agent_graph.mmd"
        mmd_path.write_text(agent_graph.get_graph().draw_mermaid(), encoding="utf-8")
        print(f"Mermaid 源码已保存: {mmd_path}")
        image_path = output_dir / "eda_agent_graph.png"
        image_bytes = agent_graph.get_graph().draw_mermaid_png()
        image_path.write_bytes(image_bytes)
        print(f"Graph 图片已保存: {image_path}")
        try:
            from IPython.display import Image, display
            display(Image(filename=str(image_path)))
        except Exception:
            pass
    except Exception as exc:
        print(f"图渲染失败: {exc}")


def _pretty_print_message(message) -> None:
    try:
        message.pretty_print()
    except UnicodeEncodeError:
        encoding = sys.stdout.encoding or "utf-8"
        text = message.pretty_repr()
        safe_text = text.encode(encoding, errors="replace").decode(encoding)
        print(safe_text)


def build_eda_agent(show_graph: bool = False):
    graph = StateGraph(GlobalState)
    graph.add_node("timer_start", make_timer_start("eda_agent"))
    graph.add_node("eda_agent", _eda_node)
    graph.add_node("tools", ToolNode(tools))
    graph.add_node("tool_state_update", _tool_state_update_node)
    graph.add_node("timer_end", make_timer_end("eda_agent"))
    graph.set_entry_point("timer_start")
    graph.add_edge("timer_start", "eda_agent")
    graph.add_conditional_edges(
        "eda_agent", _route_after_eda, {"tools": "tools", "timer_end": "timer_end"}
    )
    graph.add_edge("tools", "tool_state_update")
    graph.add_edge("tool_state_update", "eda_agent")
    graph.add_edge("timer_end", END)
    compiled = graph.compile()
    _show_graph_if_needed(compiled, show_graph=show_graph)
    return compiled


eda_agent = build_eda_agent()


