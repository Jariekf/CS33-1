"""
Supervisor Agent (质量把控与验证智能体)
职责：
  1. 接收 Worker 的代码产出与执行日志
  2. 利用 LLM 进行结构化审查打分 (Pydantic ReviewReport)
  3. 决策路由：通过 → 落盘报告 + 摘要入 Memory + 推进；不通过 → 反馈 + 重试
"""
from __future__ import annotations

import os
import json
from core.logger import get_agent_logger
from pydantic import BaseModel, Field

from core.state import GraphState
from core.llm import call_llm
from config import SUPERVISOR_PASS_THRESHOLD, MAX_OUTER_RETRY, WORKSPACE_DIR

logger = get_agent_logger("supervisor")

# ======================================================================
# 结构化审查报告定义
# ======================================================================

class ReviewReport(BaseModel):
    """Supervisor 产出的标准化审查报告。"""
    score: int = Field(description="1-5 分的质量评分，3 分为及格线")
    passed: bool = Field(description="是否允许通过当前阶段")
    feedback_for_retry: str = Field(default="", description="不通过时给出的具体修改方向")
    summary_for_memory: str = Field(default="", description="通过时写入全局 Memory 的精简摘要 (≤100字)")
    detailed_report: str = Field(default="", description="通过时落盘的完整 Markdown 审查报告")


# ======================================================================
# Prompt 模板
# ======================================================================

_SYSTEM_PROMPT_REVIEW = """\
You are an expert Data Science Supervisor. \
Your task is to review the code and execution logs naturally generated by a worker agent. \
Evaluate if the logic is correct, robust, and fulfills the required plan. \
Score the quality from 1 to 5 ({threshold} or above is passing). \
Return a structured review report in STRICT JSON.

IMPORTANT (lenient policy):
- Prefer passing if the work is broadly correct and runnable, even if there are minor style issues, minor inefficiencies, or small missing niceties.
- Only fail when there is a clear blocker: runtime error, major missing plan requirement, obviously incorrect evaluation/logic, or outputs are missing/unusable."""

_USER_PROMPT_REVIEW = """\
# PHASE #
{phase}

# PLAN #
{plan}

# WORKER CODE #
```python
{code}
```

# EXECUTION LOG #
```text
{execution_log}
```

# INSTRUCTIONS #
1. Apply a LENIENT review policy: if the implementation is broadly correct and runnable, PASS it. Do NOT fail for minor code style, minor optimizations, or non-critical improvements.
2. FAIL only if at least one CLEAR blocker is present:
   - Runtime error / crash in EXECUTION LOG (Traceback, Exception, Error)
   - Major plan item missing (a core requirement not implemented)
   - Obviously wrong evaluation or logic (e.g., data leakage, wrong target, nonsense output)
   - Outputs are missing/unusable for the next phase
3. Produce a score from 1-5. Use 4-5 for solid work; use 3 for acceptable but needs improvements; use 1-2 only for clear failures.
4. Always include evidence-based notes in `detailed_report`:
   - Plan coverage: bullet list of key plan items met / not met
   - Log evidence: quote 1-3 relevant lines or keywords from the EXECUTION LOG (or say "no log provided")
   - Risks: 1-3 potential risks even if passing (keep it short)
5. If it passes: set `passed=true`, fill `summary_for_memory` (<= 100 words), and write a helpful `detailed_report` in Markdown.
6. If it fails: set `passed=false` and write `feedback_for_retry` with this template:
   - Root cause:
   - Fix steps (2-5 bullets):
   - Re-run check:
7. Output MUST be a single JSON object and nothing else. No markdown fences, no prose, no trailing commas.
8. JSON must match this exact schema and key names:
{{
  "score": <int 1-5>,
  "passed": <boolean>,
  "feedback_for_retry": "<string>",
  "summary_for_memory": "<string>",
  "detailed_report": "<string markdown format>"
}}
"""


# ======================================================================
# Supervisor 节点
# ======================================================================

def supervisor_node(state: GraphState) -> dict:
    """
    Supervisor 的 LangGraph 节点函数。
    读取 Worker 的执行日志，调用 LLM 进行评审，并更新 State。
    """
    phase = state["current_phase"]
    code = state.get("current_code", "")
    execution_log = state.get("current_execution_log", "")
    logger.info(f"Supervisor node started for phase: {phase}.")
    plan = state.get("global_plan", {}).get(f"{phase}_plan", {})

    # ------------------------------------------------------------------
    # 调用 LLM 进行结构化审查
    # ------------------------------------------------------------------
    review = _llm_review(phase, plan, code, execution_log)
    logger.info(f"LLM review completed. Score: {review.score}, Passed: {review.passed}")

    # ------------------------------------------------------------------
    # 根据审查结果，构造状态更新
    # ------------------------------------------------------------------
    updates: dict = {"current_review": review.model_dump()}

    if review.passed:
        logger.info(f"Review passed for phase: {phase}. Writing report to output log.")
        # ---- 通过：落盘详情 + 摘要入 Memory ----
        report_path = os.path.join(WORKSPACE_DIR, f"{phase}_report.md")
        os.makedirs(WORKSPACE_DIR, exist_ok=True)
        with open(report_path, "w", encoding="utf-8") as f:
            f.write(review.detailed_report)

        memory_entry = f"[{phase}] {review.summary_for_memory} 详情见 {report_path}"
        updates["memory"] = [memory_entry]
        updates["current_error"] = ""
        updates["retry_count"] = 0
    else:
        logger.warning(f"Review failed for phase: {phase}. Feedback: {review.feedback_for_retry}")
        # ---- 不通过：附带反馈信息，累加重试计数 ----
        updates["current_error"] = review.feedback_for_retry
        updates["retry_count"] = state.get("retry_count", 0) + 1
        updates["outer_retry_total"] = state.get("outer_retry_total", 0) + 1

    return updates


# ======================================================================
# 条件路由函数 (供 graph.py 的 add_conditional_edges 调用)
# ======================================================================

def supervisor_router(state: GraphState) -> str:
    """
    根据 Supervisor 审查结果决定路由方向。
    返回:
        "pass"  — 审查通过，推进至下一阶段
        "retry" — 审查不通过，退回 Worker 重修
        "error" — 超出最大重试次数，终止流程
    """
    review = state.get("current_review")
    if review and review.get("passed"):
        return "pass"

    if state.get("retry_count", 0) >= MAX_OUTER_RETRY:
        return "error"

    return "retry"


# ======================================================================
# 私有辅助函数
# ======================================================================

def _llm_review(
    phase: str, plan: dict, code: str, execution_log: str
) -> ReviewReport:
    """
    调用 LLM 执行结构化审查。
    若调用失败则降级为不通过（要求 Worker 重试/复跑），避免把明显错误推进到下一阶段。
    """
    system_prompt = _SYSTEM_PROMPT_REVIEW.format(threshold=SUPERVISOR_PASS_THRESHOLD)
    user_prompt = _USER_PROMPT_REVIEW.format(
        phase=phase,
        plan=json.dumps(plan, ensure_ascii=False, indent=2),
        code=code,
        execution_log=execution_log,
    )
    
    try:
        reply = call_llm(system_prompt, user_prompt, agent_name="supervisor")
        if reply:
            data = _extract_first_json_object(reply)
            if isinstance(data, dict):
                review = ReviewReport(**data)

                # 最低限度的硬校验：passed 与 score/阈值一致
                if review.score < SUPERVISOR_PASS_THRESHOLD:
                    review.passed = False
                    if not review.feedback_for_retry:
                        review.feedback_for_retry = (
                            f"质量评分 {review.score} 低于阈值 {SUPERVISOR_PASS_THRESHOLD}，请按计划补全实现并重新执行验证。"
                        )

                # 额外安全门：日志中出现明显错误痕迹则不允许通过
                if _log_has_fatal_error(execution_log):
                    review.passed = False
                    if not review.feedback_for_retry:
                        review.feedback_for_retry = "执行日志中出现错误/异常痕迹（例如 Traceback/Error）。请先修复运行错误并重试。"
                return review
    except Exception as e:
        logger.error("Supervisor LLM 审查失败，降级不通过: %s", e)
        
    # 降级：默认不通过（避免把坏结果推进流程）
    return ReviewReport(
        score=max(1, SUPERVISOR_PASS_THRESHOLD - 1),
        passed=False,
        feedback_for_retry=(
            "Supervisor 审查模块解析失败/LLM 不可用，已降级为不通过以保证流程安全。"
            "请重新执行本阶段代码，确保无报错，并重试。"
        ),
        summary_for_memory="",
        detailed_report="",
    )


def _extract_first_json_object(text: str) -> dict | None:
    """
    尝试从 LLM 回复中提取第一个可解析的 JSON 对象（dict）。
    兼容回复中夹杂说明文字/多段内容的情况，比简单正则更稳。
    """
    decoder = json.JSONDecoder()
    s = text.strip()
    for i, ch in enumerate(s):
        if ch != "{":
            continue
        try:
            obj, end = decoder.raw_decode(s[i:])
            if isinstance(obj, dict):
                return obj
        except Exception:
            continue
    return None


def _log_has_fatal_error(execution_log: str) -> bool:
    """基于关键字的最低限度错误检测（避免明显异常被放行）。"""
    if not execution_log:
        return False
    log = execution_log.lower()
    fatal_markers = (
        "traceback (most recent call last)",
        "error:",
        "exception",
        "fatal",
        "segmentation fault",
        "module not found",
        "modulenotfounderror",
        "importerror",
        "keyerror",
        "valueerror",
        "typeerror",
        "indexerror",
        "zerodivisionerror",
        "filenotfounderror",
    )
    return any(m in log for m in fatal_markers)
